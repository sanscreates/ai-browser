"""Find and (reversibly) remove prebuilt binaries the mac build doesn't need.

The point is that what we ship is built from source: prebuilt executables,
libraries, objects and Java bytecode in the source tree (test fixtures,
other-platform tools, vendored blobs) are removed before building, so
nothing prebuilt can end up in the product unnoticed.

We keep:
  * the toolchains we build with (clang, rust, gn, siso, node, python,
    esbuild, ...). We use Chromium's pinned toolchain rather than a system
    one; see DECISIONS.md.
  * any file the generated build files reference as an input. `generate`
    reads every *.ninja file in the out dir, so it needs a `gn gen` first.

Sub-commands:
  generate --out out/aib   Write aib/prune/files.list from our tree.
  apply                    Move listed files into the cache (outside the
                           repo) and record a manifest.
  restore                  Move them back (do this before rebasing).
  status
"""

import argparse
import json
import os
import re
import shutil
import sys

REPO = os.path.realpath(os.path.join(os.path.dirname(__file__), '..', '..'))
LIST = os.path.join(REPO, 'aib', 'prune', 'files.list')
DEFAULT_CACHE = os.path.join(os.path.dirname(REPO), 'aib-prune-cache')

# Toolchains and build machinery we deliberately use as prebuilts.
KEEP_PREFIXES = (
    '.git', 'aib/', 'out', 'buildtools/', 'third_party/llvm-build/',
    'third_party/rust-toolchain/', 'third_party/rust-src/',
    'third_party/depot_tools/', 'third_party/node/', 'third_party/ninja/',
    'third_party/siso/', 'third_party/cpython3/', 'third_party/esbuild/',
    'third_party/devtools-frontend/src/third_party/esbuild/',
    'third_party/devtools-frontend/src/node_modules/',
    'third_party/node/node_modules/', 'tools/luci-go/',
    'third_party/libc++/', 'third_party/gperf/', 'third_party/dawn/third_party/',
    'third_party/rust/chromium_crates_io/vendor/',  # source crates
    'chrome/build/pgo_profiles/', 'third_party/swift-toolchain/',
    'third_party/devtools-frontend/src/third_party/emscripten-releases/',
    'third_party/dawn/tools/golang/',
)
BIN_EXT = {'.jar', '.class', '.dex', '.dll', '.exe', '.so', '.dylib', '.o',
           '.obj', '.lib', '.a', '.pdb', '.apk', '.aar', '.msi', '.sys'}
MAGICS = (
    b'\xcf\xfa\xed\xfe', b'\xce\xfa\xed\xfe',  # Mach-O 64/32 (LE)
    b'\xfe\xed\xfa\xcf', b'\xfe\xed\xfa\xce',  # Mach-O (BE)
    b'\x7fELF',                                # ELF
    b'!<arch>\n',                              # static library
    b'dex\n',                                  # Android dex
)
NINJA_PATH_RE = re.compile(r'\.\./\.\./([^\s:|$]+)')


def kind_of(path):
  ext = os.path.splitext(path)[1].lower()
  try:
    with open(path, 'rb') as f:
      head = f.read(8)
  except OSError:
    return None
  if head.startswith(MAGICS):
    return 'native'
  if head.startswith(b'\xca\xfe\xba\xbe'):
    # Fat Mach-O and Java class files share this magic.
    return 'java-class' if ext == '.class' else 'native'
  if head.startswith(b'MZ') and ext in ('.exe', '.dll', '.sys', '.efi', ''):
    return 'pe'
  if ext in BIN_EXT and head:
    return 'ext:' + ext
  return None


def ninja_inputs(out_dir):
  refs = set()
  for root, _, files in os.walk(out_dir):
    for f in files:
      if f.endswith('.ninja'):
        with open(os.path.join(root, f), encoding='utf-8',
                  errors='replace') as fh:
          for m in NINJA_PATH_RE.finditer(fh.read()):
            refs.add(m.group(1).replace('$ ', ' '))
  return refs


def cmd_generate(args):
  out_dir = os.path.join(REPO, args.out)
  if not os.path.exists(os.path.join(out_dir, 'build.ninja')):
    sys.exit(f'{out_dir} has no build.ninja; run gn gen first')
  needed = ninja_inputs(out_dir)
  found = []
  for dirpath, dirnames, filenames in os.walk(REPO):
    rel_dir = os.path.relpath(dirpath, REPO).replace(os.sep, '/')
    rel_dir = '' if rel_dir == '.' else rel_dir + '/'
    dirnames[:] = [d for d in dirnames
                   if not (rel_dir + d + '/').startswith(KEEP_PREFIXES)
                   and not os.path.islink(os.path.join(dirpath, d))]
    for f in filenames:
      rel = rel_dir + f
      p = os.path.join(dirpath, f)
      if os.path.islink(p) or rel in needed:
        continue
      k = kind_of(p)
      if k:
        found.append((rel, k, os.path.getsize(p)))
  found.sort()
  os.makedirs(os.path.dirname(LIST), exist_ok=True)
  total = sum(s for _, _, s in found)
  with open(LIST, 'w', encoding='utf-8') as f:
    f.write('# Generated by aib/scripts/prune_binaries.py generate. '
            'Prebuilt binaries not needed by the mac build.\n')
    for rel, k, s in found:
      f.write(f'{rel}\n')
  by_kind = {}
  for _, k, s in found:
    by_kind[k] = by_kind.get(k, 0) + 1
  print(f'{len(found)} files, {total / 1e6:.1f} MB -> {LIST}')
  print('by kind:', ', '.join(f'{k}={n}' for k, n in sorted(by_kind.items())))


def load_list():
  with open(LIST, encoding='utf-8') as f:
    return [l.rstrip('\n') for l in f if l.strip() and not l.startswith('#')]


def manifest_path(cache):
  return os.path.join(cache, 'manifest.json')


def load_manifest(cache):
  try:
    with open(manifest_path(cache), encoding='utf-8') as f:
      return json.load(f)
  except FileNotFoundError:
    return {'files': []}


def save_manifest(cache, m):
  os.makedirs(cache, exist_ok=True)
  with open(manifest_path(cache) + '.tmp', 'w', encoding='utf-8') as f:
    json.dump(m, f, indent=1)
  os.replace(manifest_path(cache) + '.tmp', manifest_path(cache))


def cmd_apply(args):
  m = load_manifest(args.cache)
  done = set(m['files'])
  moved = 0
  try:
    for rel in load_list():
      src = os.path.join(REPO, rel)
      if rel in done or not os.path.isfile(src):
        continue
      dst = os.path.join(args.cache, 'files', rel)
      os.makedirs(os.path.dirname(dst), exist_ok=True)
      m['files'].append(rel)
      shutil.move(src, dst)
      moved += 1
  finally:
    save_manifest(args.cache, m)
  print(f'pruned {moved} files (total in cache: {len(m["files"])})')


def cmd_restore(args):
  m = load_manifest(args.cache)
  restored = 0
  for rel in m['files']:
    src = os.path.join(args.cache, 'files', rel)
    dst = os.path.join(REPO, rel)
    if os.path.exists(src) and not os.path.exists(dst):
      os.makedirs(os.path.dirname(dst), exist_ok=True)
      shutil.move(src, dst)
      restored += 1
  m['files'] = []
  save_manifest(args.cache, m)
  print(f'restored {restored} files')


def cmd_status(args):
  n = len(load_manifest(args.cache)['files'])
  print('pruned' if n else 'clean', f'({n} files in cache)')


def main():
  p = argparse.ArgumentParser(description=__doc__,
                              formatter_class=argparse.RawTextHelpFormatter)
  p.add_argument('--cache', default=DEFAULT_CACHE)
  sub = p.add_subparsers(dest='cmd', required=True)
  g = sub.add_parser('generate')
  g.add_argument('--out', default='out/aib')
  sub.add_parser('apply')
  sub.add_parser('restore')
  sub.add_parser('status')
  args = p.parse_args()
  return {'generate': cmd_generate, 'apply': cmd_apply,
          'restore': cmd_restore, 'status': cmd_status}[args.cmd](args) or 0


if __name__ == '__main__':
  sys.exit(main())
